/**
 * Les questions brise-glace.
 *
 * L'écran vide de la conversation dit déjà l'essentiel : « une question
 * précise marche mieux qu'un salut ». Ces questions sont la version
 * utilisable de ce conseil.
 *
 * Elles sont ouvertes — aucune ne se répond par oui ou par non —, elles
 * ne demandent rien d'intime, et aucune ne porte sur le physique. Une
 * question brise-glace doit lancer une conversation, pas un entretien.
 */
export const BRISE_GLACE: string[] = [
  "Qu’est-ce qui t’a occupé l’esprit cette semaine ?",
  "Quel est le dernier endroit qui t’a vraiment plu, et pourquoi ?",
  "Tu préfères les dimanches qui ne servent à rien ou ceux qu’on remplit ?",
  "Qu’est-ce que tu as appris récemment qui t’a surpris ?",
  "Si tu avais trois jours libres demain, tu en ferais quoi ?",
  "Qu’est-ce que tu écoutes en ce moment ?",
  "Il y a un film ou un livre que tu recommandes à tout le monde ?",
  "C’est quoi, pour toi, une bonne soirée ?",
  "Qu’est-ce qui te fait rire, même quand la journée a été longue ?",
  "Tu es plutôt du matin ou tu revis à la nuit tombée ?",
  "Quelle est la chose la plus spontanée que tu aies faite cette année ?",
  "Qu’est-ce que tu ferais si le travail n’était pas une question ?",
  "Un endroit où tu retournerais sans hésiter ?",
  "Qu’est-ce qui t’a donné envie de t’inscrire ici ?",
];
